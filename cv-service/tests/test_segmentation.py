"""Segmentation model smoke test — skips cleanly if the model hasn't
been trained (it's gitignored, generated by
`cv-service/training/train_segmentation.py`, not committed). Unlike
the rest of `cv-service/tests/`, this does NOT assert accuracy — it
asserts the trained artifact loads and produces well-formed output.
Accuracy claims belong in `cv-service/models/segmentation_v1/results.csv`
(ultralytics' own validation metrics) with the domain-gap caveat from
`segmentation/segment_uniform.py`'s module docstring, not in this test.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

CV_SERVICE_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(CV_SERVICE_ROOT))

from segmentation.segment_uniform import segment_uniform  # noqa: E402

MODEL_PATH = CV_SERVICE_ROOT / "models" / "segmentation_v1" / "weights" / "best.pt"
FIXTURE = CV_SERVICE_ROOT / "tests" / "fixtures" / "rendered_army_no3_male_front.jpg"


@pytest.fixture(scope="module")
def result():
    if not MODEL_PATH.exists():
        pytest.skip(f"{MODEL_PATH} not present — run generate_segmentation_dataset.py + train_segmentation.py first")
    if not FIXTURE.exists():
        pytest.skip(f"{FIXTURE} not present")
    return segment_uniform(str(FIXTURE))


def test_produces_at_least_one_region(result):
    assert len(result.regions) > 0


def test_shirt_and_trousers_detected_on_the_reference_render(result):
    """The reference fixture is a front-on render of the exact body
    this model was trained on — this is the easiest possible case, not
    a real-world accuracy claim. If it can't find shirt/trousers here,
    it can't find them anywhere."""
    class_names = {r.class_name for r in result.regions}
    assert "shirt" in class_names
    assert "trousers" in class_names


def test_masks_are_well_formed(result):
    for region in result.regions:
        assert region.mask.shape == (result.image_height, result.image_width)
        assert region.mask.dtype == bool
        assert region.mask.sum() > 0
        assert 0.0 <= region.confidence <= 1.0


def test_coverage_fraction_is_bounded(result):
    for class_name in {r.class_name for r in result.regions}:
        fraction = result.coverage_fraction(class_name)
        assert 0.0 <= fraction <= 1.0
