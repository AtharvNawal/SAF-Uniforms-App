"""Builds the versioned ground-truth label schema.

The schema's two closed vocabularies — which anchors an annotator must
click, and which accessory classes they may outline — are **not**
hand-copied here. They're imported from the two modules that already own
them, so a schema regen (`python -m cv_service.labeling.schema`) is the
only thing standing between this file and drift whenever either list
changes:

- `SOCKET_NAMES` (15 names) from `utils.extract_anchors` — the same list
  the reference-body anchor extraction and the doctrine rule files key
  against.
- `CLASSES` (9 names) from `training.generate_segmentation_dataset` — the
  same list the trained YOLOv8n-seg model's output classes use.

Run standalone to (re)write `cv-service/data/schemas/ground_truth.v1.schema.json`:

    .venv-tools/bin/python cv-service/labeling/schema.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "cv-service"))

from training.generate_segmentation_dataset import CLASSES as ACCESSORY_CLASSES  # noqa: E402
from utils.extract_anchors import SOCKET_NAMES as ANCHOR_NAMES  # noqa: E402

SCHEMA_VERSION = 1
ANGLES = ["front", "back", "left_3q", "right_3q"]
LIGHTING_CONDITIONS = ["indoor_bright", "indoor_dim", "outdoor_overcast", "outdoor_sunny"]

SCHEMA_PATH = REPO_ROOT / "cv-service" / "data" / "schemas" / "ground_truth.v1.schema.json"


def build_schema() -> dict:
    """Returns the JSON Schema (draft 2020-12) dict for one ground-truth
    label file — one photo's worth of 15 clicked anchors plus zero or
    more accessory polygons."""
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "cv-service/data/schemas/ground_truth.v1.schema.json",
        "title": "cv-service real-photo ground-truth label",
        "description": (
            "One label file per photo. Generated by "
            "cv-service/labeling/schema.py from utils.extract_anchors."
            "SOCKET_NAMES and training.generate_segmentation_dataset.CLASSES "
            "— do not hand-edit; regenerate instead if those lists change."
        ),
        "type": "object",
        "additionalProperties": False,
        "required": [
            "schema_version",
            "photo_id",
            "source_path",
            "subject_id",
            "angle",
            "lighting",
            "image_width",
            "image_height",
            "is_synthetic_stand_in",
            "annotator",
            "labeled_at",
            "anchors",
            "accessories",
        ],
        "properties": {
            "schema_version": {"const": SCHEMA_VERSION},
            "photo_id": {"type": "string", "minLength": 1},
            "source_path": {"type": "string", "minLength": 1},
            "subject_id": {"type": "string", "pattern": "^[A-Za-z0-9_-]+$"},
            "angle": {"enum": ANGLES},
            "lighting": {"enum": LIGHTING_CONDITIONS},
            "image_width": {"type": "integer", "exclusiveMinimum": 0},
            "image_height": {"type": "integer", "exclusiveMinimum": 0},
            "is_synthetic_stand_in": {
                "type": "boolean",
                "description": (
                    "Required, not optional: true for a rendered/placeholder "
                    "stand-in, false only for an actual photograph of a real "
                    "person. Never inferred from the filename alone."
                ),
            },
            "annotator": {"type": "string", "minLength": 1},
            "labeled_at": {"type": "string", "format": "date-time"},
            "notes": {"type": "string"},
            "anchors": {
                "type": "object",
                "additionalProperties": False,
                "required": ANCHOR_NAMES,
                "properties": {name: {"$ref": "#/$defs/anchor_point"} for name in ANCHOR_NAMES},
            },
            "accessories": {
                "type": "array",
                "items": {"$ref": "#/$defs/accessory_instance"},
            },
        },
        "$defs": {
            "anchor_point": {
                "type": "object",
                "additionalProperties": False,
                "required": ["visible"],
                "properties": {
                    "x_px": {"type": "number"},
                    "y_px": {"type": "number"},
                    "visible": {
                        "type": "boolean",
                        "description": "False when the annotator could not see/click this anchor (out of frame, occluded).",
                    },
                },
                "if": {"properties": {"visible": {"const": True}}},
                "then": {"required": ["x_px", "y_px"]},
            },
            "accessory_instance": {
                "type": "object",
                "additionalProperties": False,
                "required": ["class_name", "present"],
                "properties": {
                    "class_name": {"enum": ACCESSORY_CLASSES},
                    "side": {"enum": ["left", "right", "center"]},
                    "present": {"type": "boolean"},
                    "polygon_px": {
                        "type": "array",
                        "minItems": 3,
                        "items": {
                            "type": "array",
                            "minItems": 2,
                            "maxItems": 2,
                            "items": {"type": "number"},
                        },
                    },
                },
                "if": {"properties": {"present": {"const": True}}},
                "then": {"required": ["polygon_px"]},
            },
        },
    }


def write_schema(out_path: Path = SCHEMA_PATH) -> None:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(build_schema(), indent=2) + "\n")
    print(f"wrote {out_path}")


if __name__ == "__main__":
    write_schema()
